import Foundation
@testable import PastoCore
import PastoFoundation
import Testing

struct CaptureRulesTests {
    private let ephemeral = EphemeralDefaults()
    private var config: ConfigStore { ConfigStore(defaults: ephemeral.defaults) }

    /// The rules a fresh install has.
    private var rules: CaptureRules { CaptureRules(config: config) }

    private func decision(
        _ rules: CaptureRules,
        from application: String? = "com.apple.Safari",
        types: [String] = ["public.utf8-plain-text"],
        declaredSource: String? = nil
    ) -> CaptureRules.Decision {
        rules.decision(frontmostBundleIdentifier: application, types: types) { declaredSource }
    }

    // MARK: - Applications

    @Test func capturesFromAnOrdinaryApplication() {
        #expect(decision(rules) == .capture)
    }

    @Test func skipsWhenNothingIsInFront() {
        #expect(decision(rules, from: nil) == .skip(.undefinedFrontmostApplication))
    }

    @Test(arguments: [
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7-helper",
        "com.bitwarden.desktop",
        "com.nordpass.macos.NordPass",
    ])
    func ignoresPasswordManagersBySubstring(bundleIdentifier: String) {
        #expect(decision(rules, from: bundleIdentifier) == .skip(.ignoredApplication(bundleIdentifier)))
    }

    @Test func matchingIsCaseSensitive() {
        #expect(decision(rules, from: "com.apple.passwords") == .capture)
    }

    @Test func theUsersListReplacesTheDefaultOne() {
        config.set(["com.example.Secrets"], for: .ignoredBundleIdentifiers)

        #expect(decision(rules, from: "com.example.Secrets.helper") == .skip(.ignoredApplication("com.example.Secrets.helper")))
        #expect(decision(rules, from: "com.apple.Passwords") == .capture)
    }

    @Test func firefoxDeveloperEditionOnlyMatchesExactly() {
        let firefox = CaptureRules(ignoredBundleIdentifiers: ["org.mozilla.firefox"], ignoredPasteboardTypes: [])
        #expect(firefox.isIgnored(bundleIdentifier: "org.mozilla.firefox"))
        #expect(firefox.isIgnored(bundleIdentifier: "org.mozilla.firefoxbeta"))
        #expect(!firefox.isIgnored(bundleIdentifier: "org.mozilla.firefoxdeveloperedition"))

        let developerEdition = CaptureRules(
            ignoredBundleIdentifiers: ["org.mozilla.firefoxdeveloperedition"],
            ignoredPasteboardTypes: []
        )
        #expect(developerEdition.isIgnored(bundleIdentifier: "org.mozilla.firefoxdeveloperedition"))
    }

    @Test func anEmptyEntryIgnoresNothing() {
        let rules = CaptureRules(ignoredBundleIdentifiers: [""], ignoredPasteboardTypes: [""])

        #expect(decision(rules) == .capture)
    }

    // MARK: - Types

    @Test(arguments: [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.ConcealedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ])
    func oneIgnoredTypeDropsTheWholeChange(type: String) {
        let types = ["public.utf8-plain-text", "public.rtf", type]

        #expect(decision(rules, types: types) == .skip(.ignoredType(type)))
    }

    @Test func aTypeIsIgnoredWhenItContainsAnEntryOrAnEntryContainsIt() {
        let type = "org.nspasteboard.ConcealedType.v2"

        #expect(decision(rules, types: [type]) == .skip(.ignoredType(type)))
        #expect(decision(rules, types: ["org.nspasteboard"]) == .skip(.ignoredType("org.nspasteboard")))
        #expect(decision(rules, types: ["public.utf8-plain-text"]) == .capture)
    }

    // MARK: - Declared source

    @Test func contentDeclaredAsComingFromAnIgnoredApplicationIsSkipped() {
        let types = ["public.utf8-plain-text", "org.nspasteboard.source"]

        #expect(decision(rules, types: types, declaredSource: "com.lastpass.LastPass") == .skip(.ignoredSource("com.lastpass.LastPass")))
        #expect(decision(rules, types: types, declaredSource: "com.apple.Notes") == .capture)
        #expect(decision(rules, types: types, declaredSource: "") == .capture)
        #expect(decision(rules, types: types, declaredSource: nil) == .capture)
    }

    @Test func theDeclaredSourceIsOnlyReadWhenItsTypeIsPresent() {
        var reads = 0
        let outcome = rules.decision(frontmostBundleIdentifier: "com.apple.Safari", types: ["public.utf8-plain-text"]) {
            reads += 1
            return "com.lastpass.LastPass"
        }

        #expect(outcome == .capture)
        #expect(reads == 0)
    }

    @Test func pastosOwnMarkerDoesNotVetoACapture() {
        #expect(decision(rules, types: ["public.utf8-plain-text", PasteboardMarker.ownWrite]) == .capture)
    }
}

struct PasteboardTypeFilterTests {
    private func read(_ types: [String], from application: String? = "com.apple.Safari") -> [String] {
        let filter = PasteboardTypeFilter(types: types, frontmostBundleIdentifier: application)
        return types.filter(filter.shouldRead)
    }

    @Test func readsEverythingOrdinary() {
        let types = ["public.html", "public.rtf", "public.utf8-plain-text", "com.example.private"]

        #expect(read(types) == types)
    }

    @Test func universalClipboardContentIsReadAsTextOnly() {
        let types = [
            "com.apple.is-remote-clipboard", "public.png", "public.html", "public.rtf",
            "public.utf8-plain-text", "public.text", "public.utf16-plain-text",
        ]

        #expect(read(types) == ["public.rtf", "public.utf8-plain-text", "public.text"])
    }

    @Test func excelIsReadAsPlainTextOnly() {
        let types = ["public.tiff", "public.rtf", "public.html", "public.utf16-plain-text", "public.utf8-plain-text"]

        #expect(read(types, from: "com.microsoft.Excel") == ["public.utf16-plain-text", "public.utf8-plain-text"])
        #expect(read(types, from: "com.microsoft.Word") == types)
    }

    @Test func anImageLosesTheURLOfItsFile() {
        #expect(read(["public.file-url", "public.png", "public.tiff"]) == ["public.png", "public.tiff"])
        // Only PNG has this effect.
        #expect(read(["public.file-url", "public.tiff"]) == ["public.file-url", "public.tiff"])
    }

    @Test func officeLinkTypesAreNotRead() {
        let types = [
            "com.microsoft.ObjectLink", "com.microsoft.Link-Source", "com.microsoft.DataObject", "public.utf8-plain-text",
        ]

        // The data object carries the content itself, so it is read.
        #expect(read(types, from: "com.microsoft.Word") == ["com.microsoft.DataObject", "public.utf8-plain-text"])
    }
}
