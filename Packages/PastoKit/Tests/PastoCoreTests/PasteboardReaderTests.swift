import Foundation
@_spi(Benchmarks) @testable import PastoCore
import PastoFoundation
import Testing

struct PasteboardReaderTests {
    private let source = FakePasteboardSource()
    private let rules = CaptureRules(
        ignoredBundleIdentifiers: ["com.example.Secrets"],
        ignoredPasteboardTypes: ["org.nspasteboard.ConcealedType"]
    )

    private func read(maximumSize: Int = 1 << 30, from application: String? = "com.apple.Safari") -> PasteboardReader.Outcome {
        PasteboardReader(maximumSize: maximumSize).read(source, frontmostBundleIdentifier: application, rules: rules)
    }

    private func bytes(_ count: Int) -> Data {
        Data(repeating: 7, count: count)
    }

    @Test func readsEveryRepresentationInOrder() {
        let item = PasteboardItemSnapshot(strings: ["public.html": "<b>hi</b>", "public.utf8-plain-text": "hi"])
        source.copy([item, .text("second")])

        #expect(read() == .read(items: [item, .text("second")], pasteboardWasEmpty: false))
        // Fetching is what makes an owner produce data it only promised.
        #expect(source.requestedTypes == ["public.html", "public.utf8-plain-text", "public.utf8-plain-text"])
    }

    @Test func doesNotTouchThePasteboardWithoutAccess() {
        source.copy([.text("hi")])
        source.setAllowsProgrammaticReads(false)

        #expect(read() == .accessNeeded)
        #expect(source.requestedTypes.isEmpty)
    }

    @Test func reportsAPasteboardThatCannotBeRead() {
        source.setReadable(false)

        #expect(read() == .unreadable)
    }

    @Test func aVetoedChangeIsNeverFetched() {
        source.copy([PasteboardItemSnapshot(strings: ["public.utf8-plain-text": "hunter2", "org.nspasteboard.ConcealedType": ""])])
        #expect(read() == .skipped(.ignoredType("org.nspasteboard.ConcealedType")))

        source.copy([.text("hunter2")])
        #expect(read(from: "com.example.Secrets") == .skipped(.ignoredApplication("com.example.Secrets")))
        #expect(read(from: nil) == .skipped(.undefinedFrontmostApplication))

        source.copy([PasteboardItemSnapshot(strings: ["public.utf8-plain-text": "hunter2", "org.nspasteboard.source": "com.example.Secrets"])])
        #expect(read() == .skipped(.ignoredSource("com.example.Secrets")))

        #expect(source.requestedTypes.isEmpty)
    }

    /// The rules as a new user has them: the nspasteboard.org markers and the password managers.
    @Test(arguments: [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
    ])
    func concealedTransientAndGeneratedContentIsNeverFetched(marker: String) {
        let rules = CaptureRules(ignoredBundleIdentifiers: [], ignoredPasteboardTypes: ConfigKey.ignoredPasteboardTypes.defaultValue)
        // The marker can come on any item, after the content.
        source.copy([
            .text("not this one"),
            PasteboardItemSnapshot(strings: ["public.utf8-plain-text": "hunter2", "public.rtf": "{\\rtf1 hunter2}", marker: ""]),
        ])

        let outcome = PasteboardReader(maximumSize: 1 << 30).read(source, frontmostBundleIdentifier: "com.apple.Safari", rules: rules)

        #expect(outcome == .skipped(.ignoredType(marker)))
        #expect(source.requestedTypes.isEmpty)
    }

    @Test(arguments: ["com.apple.Passwords", "com.1password.1password", "com.bitwarden.desktop"])
    func nothingCopiedInAPasswordManagerIsFetched(application: String) {
        let rules = CaptureRules(ignoredBundleIdentifiers: ConfigKey.ignoredBundleIdentifiers.defaultValue, ignoredPasteboardTypes: [])
        source.copy([.text("hunter2")])

        let outcome = PasteboardReader(maximumSize: 1 << 30).read(source, frontmostBundleIdentifier: application, rules: rules)

        #expect(outcome == .skipped(.ignoredApplication(application)))
        #expect(source.requestedTypes.isEmpty)
    }

    @Test func filteredTypesAreNeitherFetchedNorKept() {
        source.copy([PasteboardItemSnapshot(strings: ["public.file-url": "file:///tmp/a.png", "public.png": "png"])])

        #expect(read() == .read(items: [PasteboardItemSnapshot(strings: ["public.png": "png"])], pasteboardWasEmpty: false))
        #expect(source.requestedTypes == ["public.png"])
    }

    @Test func keepsWhatFitsInTheSizeLimitAndGoesOn() {
        source.copy([
            PasteboardItemSnapshot(["com.example.a": bytes(6), "com.example.b": bytes(6)]),
            PasteboardItemSnapshot(["com.example.c": bytes(4), "com.example.d": bytes(1)]),
        ])

        // 6 fits; 6 more would make 12; 4 makes exactly 10, which is still allowed; nothing fits after.
        // The limit is shared by all the items, and what was skipped does not count.
        #expect(read(maximumSize: 10) == .read(
            items: [PasteboardItemSnapshot(["com.example.a": bytes(6)]), PasteboardItemSnapshot(["com.example.c": bytes(4)])],
            pasteboardWasEmpty: false
        ))
        #expect(source.requestedTypes == ["com.example.a", "com.example.b", "com.example.c", "com.example.d"])
    }

    @Test func anItemLeftWithNothingIsDropped() {
        source.copy([
            PasteboardItemSnapshot(strings: ["com.microsoft.ObjectLink": "link"]),
            PasteboardItemSnapshot(types: ["public.promised"], dataByType: [:]),
            .text("kept"),
        ])

        #expect(read() == .read(items: [.text("kept")], pasteboardWasEmpty: false))
    }

    @Test func tellsAnEmptyPasteboardFromOneWithNothingWorthKeeping() {
        source.copy([])
        #expect(read() == .read(items: [], pasteboardWasEmpty: true))

        source.copy([PasteboardItemSnapshot(strings: ["com.microsoft.ObjectLink": "link"])])
        #expect(read() == .read(items: [], pasteboardWasEmpty: false))
    }
}
