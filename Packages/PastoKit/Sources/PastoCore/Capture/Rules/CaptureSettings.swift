import PastoFoundation

// The settings capture reads and writes, and their `UserDefaults` keys.

extension ConfigKey where Value == [String] {
    /// Applications whose copies are never captured. An application matches when its bundle
    /// identifier *contains* an entry, which is why some entries are partial.
    ///
    /// The list is one setting: the user edits this list, and until they do it is the default one.
    public static var ignoredBundleIdentifiers: ConfigKey<[String]> {
        ConfigKey("ignoredBundleIdentifiers", default: [
            "com.apple.Passwords",
            "com.apple.keychainaccess",
            "com.1password",
            "com.agilebits.onepassword-osx",
            "com.agilebits.onepassword4",
            "com.agilebits.onepassword7",
            "com.lastpass.LastPass",
            "com.dashlane.Dashlane",
            "com.bitwarden.desktop",
            "in.sinew.Enpass-Desktop",
            "com.SiberSystems.RoboForm",
            "com.callpod.keepermac",
            "com.keepersecurity",
            ".nordpass",
        ])
    }

    /// Pasteboard types that mark a change as not worth keeping: the nspasteboard.org markers for
    /// transient, generated and concealed content, and the ones older text expanders use.
    public static var ignoredPasteboardTypes: ConfigKey<[String]> {
        ConfigKey("ignoredPasteboardTypes", default: [
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "org.nspasteboard.ConcealedType",
            "de.petermaurer.TransientPasteboardType",
            "com.typeit4me.clipping",
            "Pasteboard generator type",
        ])
    }
}

extension ConfigKey where Value == Int {
    /// The change count of the last pasteboard content Pasto dealt with: stored after a capture,
    /// after a read that found the pasteboard empty and after Pasto's own writes. 0 means "never
    /// stored".
    public static var pasteboardChangeToken: ConfigKey<Int> {
        ConfigKey("pasteboard-change-token", default: 0)
    }

    /// How many pasteboard reads have been delivered since the settings were created.
    public static var pasteboardSyncCount: ConfigKey<Int> {
        ConfigKey("pasteboardSyncCount", default: 0)
    }
}
