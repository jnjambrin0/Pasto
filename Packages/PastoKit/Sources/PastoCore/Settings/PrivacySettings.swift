import PastoFoundation

// Settings › Privacy. The two "ignore … content" switches have no key of their own: they edit
// `ignoredPasteboardTypes`.

extension ConfigKey where Value == Bool {
    /// "Show During Screen Sharing": whether Pasto's windows appear in screen captures and
    /// shared screens. The app applies it to every window as `NSWindow.sharingType`.
    public static var isScreenSharingContentVisible: ConfigKey<Bool> {
        ConfigKey("isScreenSharingContentVisible", default: true)
    }

    /// Fetch the title and image of copied links, and show them on link cards.
    public static var isLinkPreviewsEnabled: ConfigKey<Bool> {
        ConfigKey("isLinkPreviewsEnabled", default: true)
    }
}

/// The pasteboard markers the Privacy switches add to or remove from `ignoredPasteboardTypes`.
/// The other default entries of that setting have no switch and stay ignored.
public enum IgnoredContentType: String, Sendable, CaseIterable {
    /// Passwords and other secrets, as password managers mark them.
    case confidential = "org.nspasteboard.ConcealedType"
    /// Content an application generated on its own, without the user copying it.
    case transient = "org.nspasteboard.AutoGeneratedType"
}
